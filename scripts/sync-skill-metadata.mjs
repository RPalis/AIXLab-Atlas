#!/usr/bin/env node
// Generates skills/<name>/agents/openai.yaml (Codex UI metadata and invocation policy) from each
// SKILL.md, so the two cannot drift. A skill with disable-model-invocation: true gets
// allow_implicit_invocation: false, which is the Codex equivalent.
//   node scripts/sync-skill-metadata.mjs          # write
//   node scripts/sync-skill-metadata.mjs --check  # exit 1 if any file would change
import fs from 'node:fs';
import path from 'node:path';
import { readSkill } from './lib/frontmatter.mjs';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..', 'skills');
const check = process.argv.includes('--check');
let changed = 0;
const title = n => n.split('-').map(w => w[0].toUpperCase() + w.slice(1)).join(' ');
const q = s => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';

for (const name of fs.readdirSync(ROOT).filter(n => fs.existsSync(path.join(ROOT, n, 'SKILL.md')))) {
  const { fm } = readSkill(path.join(ROOT, name, 'SKILL.md'));
  const first = fm.description.split(/(?<=\.)\s/)[0];
  const short = first.length > 110 ? first.slice(0, 107).replace(/\s+\S*$/, '') + '...' : first;
  const implicit = fm['disable-model-invocation'] === 'true' ? 'false' : 'true';
  const yaml = `# Generated by scripts/sync-skill-metadata.mjs. Do not edit by hand.
interface:
  display_name: ${q(title(name))}
  short_description: ${q(short)}
policy:
  allow_implicit_invocation: ${implicit}
`;
  const out = path.join(ROOT, name, 'agents', 'openai.yaml');
  const cur = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (cur !== yaml) {
    changed++;
    if (!check) { fs.mkdirSync(path.dirname(out), { recursive: true }); fs.writeFileSync(out, yaml); }
  }
}
console.log(check ? `${changed} files out of date` : `${changed} files written`);
process.exit(check && changed ? 1 : 0);
